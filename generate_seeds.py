# Main
# ---------------------------------------------------------------------------
def main():
    print("=" * 60)
    print("  STUD.io — Seed Generator")
    print("=" * 60)

    SEED_DIR.mkdir(parents=True, exist_ok=True)
    for f in SEED_DIR.glob("*.sql"):
        f.unlink()

    generate_brands()
    generate_workstations()
    generate_workflow_tools()
    generate_measurement_tools()
    generate_reference_tools()
