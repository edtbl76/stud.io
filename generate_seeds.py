#!/usr/bin/env python3
"""
STUD.io — Seed Generator

Reads CSV files from csv/ and generates SQL seed files in sql/seeds/.
Safe to re-run — seed files are fully regenerated each time.

Usage:
    python generate_seeds.py
"""

import csv
from pathlib import Path

CSV_DIR  = Path(__file__).parent / "csv"
SEED_DIR = Path(__file__).parent / "sql" / "seeds"


def clean(val):
    if val is None:
        return None
    v = str(val).strip()
    return v if v else None


def escape(val):
    """Escape a value for SQL insertion."""
    if val is None:
        return "NULL"
    return "'" + str(val).replace("'", "''") + "'"


def escape_array(val, cast):
    """Escape a comma-separated value as a PostgreSQL array literal."""
    if not val:
        return f"NULL::{cast}[]"
    # Strip outer curly braces if already present in the CSV value
    val = val.strip().lstrip("{").rstrip("}")
    elements = [v.strip() for v in val.split(",") if v.strip()]
    return "'{" + ",".join(elements) + "}'::" + cast + "[]"


def log(msg):
    print(f"  {msg}")


def seed_header(table, csv_file):
    return [
        "-- =============================================================================",
        f"-- Seed: {table}",
        "-- Generated by generate_seeds.py — do not edit directly",
        f"-- Edit csv/{csv_file} instead",
        "-- =============================================================================",
        "",
    ]


def tool_row(table, id_col, id_val, brand_id, name, version,
             tool_types, plugin_formats, description, workflow_notes, tags):
    return (
        f"INSERT INTO {table}"
        f" ({id_col}, brand_id, name, version, tool_types, plugin_formats, description, workflow_notes, tags)"
        f" VALUES ("
        f"{escape(id_val)}, "
        f"{escape(brand_id) if brand_id else 'NULL'}, "
        f"{escape(name)}, "
        f"{escape(version)}, "
        f"{escape_array(tool_types, 'tool_type')}, "
        f"{escape_array(plugin_formats, 'plugin_format')}, "
        f"{escape(description)}, "
        f"{escape(workflow_notes)}, "
        f"{escape_array(tags, 'tag_type')}"
        f") ON CONFLICT ({id_col}) DO UPDATE SET"
        f" version = EXCLUDED.version,"
        f" description = EXCLUDED.description,"
        f" workflow_notes = EXCLUDED.workflow_notes,"
        f" updated_at = NOW();"
    )


def read_tool_csv(src, id_col):
    rows = []
    with open(src, newline='', encoding='utf-8') as f:
        for row in csv.DictReader(f):
            name = clean(row.get("name"))
            if not name:
                continue
            rows.append((
                clean(row.get(id_col)),
                clean(row.get("brand_id")),
                name,
                clean(row.get("version")),
                clean(row.get("tool_types")),
                clean(row.get("plugin_formats")),
                clean(row.get("description")),
                clean(row.get("workflow_notes")),
                clean(row.get("tags")),
            ))
    return rows


# ---------------------------------------------------------------------------
# Brands
# ---------------------------------------------------------------------------
def generate_brands():
    src  = CSV_DIR / "brands.csv"
    dest = SEED_DIR / "01_brands.sql"

    rows = []
    with open(src, newline='', encoding='utf-8') as f:
        for row in csv.DictReader(f):
            brand_id    = clean(row.get("brand_id"))
            name        = clean(row.get("name"))
            common_name = clean(row.get("common_name"))
            entity_type = clean(row.get("entity_type")) or "Manufacturer"
            website     = clean(row.get("website"))
            if not name:
                continue
            rows.append((brand_id, name, common_name, entity_type, website))

    lines = seed_header("brands", "brands.csv")

    for brand_id, name, common_name, entity_type, website in rows:
        lines.append(
            f"INSERT INTO brands (brand_id, name, common_name, entity_type, website)"
            f" VALUES ({escape(brand_id)}, {escape(name)}, {escape(common_name)}, {escape(entity_type)}, {escape(website)})"
            f" ON CONFLICT (brand_id) DO UPDATE SET"
            f" website = EXCLUDED.website,"
            f" entity_type = EXCLUDED.entity_type,"
            f" updated_at = NOW();"
            f"  -- common_name intentionally not updated (manually maintained)"
        )

    lines.append("")
    dest.write_text("\n".join(lines), encoding="utf-8")
    log(f"{len(rows)} brands → {dest.name}")


# ---------------------------------------------------------------------------
# Workstations
# ---------------------------------------------------------------------------
def generate_workstations():
    src  = CSV_DIR / "workstations.csv"
    dest = SEED_DIR / "02_workstations.sql"
    rows = read_tool_csv(src, "workstation_id")
    lines = seed_header("workstations", "workstations.csv")
    for r in rows:
        lines.append(tool_row("workstations", "workstation_id", *r))
    lines.append("")
    dest.write_text("\n".join(lines), encoding="utf-8")
    log(f"{len(rows)} workstations → {dest.name}")


